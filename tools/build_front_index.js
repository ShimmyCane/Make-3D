// Writes js/front_index.js: a small list of every built-in scene (id, name, project, updated, parts, moves).
// The front page (index.html) reads this instead of the 37 MB sample bundle. Run it after build_samples.js:
//   node tools/build_front_index.js
// Read only: it loads js/samples.bundle.js into a stub window and writes one file.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const bundlePath = path.join(root, 'js/samples.bundle.js');
const outPath = path.join(root, 'js/front_index.js');

const win = {};
vm.runInNewContext(fs.readFileSync(bundlePath, 'utf8'), { window: win, console });
const samples = win.M3D_SAMPLES || {};

const rows = Object.keys(samples).map((id) => {
  const b = samples[id];
  const l = b.listing || {};
  const name = (b.history && b.history.header && b.history.header.name) || id;
  const project = l.project || name.replace(/\s+V\d+(\.\d+)?$/i, '').trim();
  const parts = b.model ? b.model.objects.length : b.history.operations.length;
  return {
    id, name, project,
    updated: l.updated || l.created || '',
    parts,
    moves: !!b.motion,
  };
});

const js = '// Generated by tools/build_front_index.js from js/samples.bundle.js. Do not edit by hand.\n'
  + 'window.M3D_FRONT_INDEX = ' + JSON.stringify(rows) + ';\n';
fs.writeFileSync(outPath, js);
console.log(`wrote ${rows.length} scenes to js/front_index.js (${js.length} bytes)`);
