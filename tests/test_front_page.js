// Guards the split: index.html is the light front page; viewer.html holds the 3-D engine and the samples.
// Run: node tests/test_front_page.js
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const scripts = (html) => [...html.matchAll(/<script src="([^"]+)"/g)].map((m) => m[1].split('?')[0]);

let n = 0;
const t = (name, fn) => { fn(); n++; console.log('ok', name); };

const front = read('index.html');
const viewer = read('viewer.html');

t('the front page loads no sample bundle, no 3-D engine and no cloud library', () => {
  const s = scripts(front);
  assert.deepStrictEqual(s, ['js/ui/front.js', 'js/front_index.js', 'js/ui/front_page.js']);
  for (const bad of ['samples.bundle', 'three.min', 'viewer.js', 'app.js', 'supabase', 'cloud.js']) {
    assert.ok(!s.some((x) => x.includes(bad)), `front page loads ${bad}`);
  }
});

t('the viewer page loads the engine and the sample bundle; it has no front overlay', () => {
  const s = scripts(viewer);
  assert.ok(s.includes('js/samples.bundle.js'));
  assert.ok(s.includes('js/viewer/viewer.js'));
  assert.ok(s.includes('js/ui/app.js'));
  assert.ok(!viewer.includes('id="front"'));
  assert.ok(!viewer.includes('id="reqPanel"'));
  assert.ok(viewer.includes('href="index.html"'), 'the Front page button links to index.html');
});

t('the front page index is a generated file with one entry per scene', () => {
  const src = read('js/front_index.js');
  assert.ok(src.startsWith('// Generated by tools/build_front_index.js'));
  const json = src.slice(src.indexOf('= ') + 2).replace(/;\s*$/, '');
  const list = JSON.parse(json);
  assert.ok(Array.isArray(list) && list.length > 100, 'expected the built-in scenes');
  for (const e of list) {
    assert.ok(e.id && e.name && e.project, 'entry needs id, name and project');
    assert.ok(Number.isInteger(e.parts) && e.parts >= 0, 'parts is a count');
  }
  const ids = new Set(list.map((e) => e.id));
  assert.strictEqual(ids.size, list.length, 'ids are unique');
});

t('the index lists exactly the scenes in the bundle (rebuild with tools/build_front_index.js after build_samples.js)', () => {
  const win = {};
  vm.runInNewContext(read('js/samples.bundle.js'), { window: win });
  const bundleIds = Object.keys(win.M3D_SAMPLES).sort();
  const indexIds = JSON.parse(read('js/front_index.js').split('= ')[1].replace(/;\s*$/, '')).map((e) => e.id).sort();
  assert.deepStrictEqual(indexIds, bundleIds);
});

t('the index file is small compared with the bundle', () => {
  const idx = fs.statSync(path.join(root, 'js/front_index.js')).size;
  const bundle = fs.statSync(path.join(root, 'js/samples.bundle.js')).size;
  assert.ok(idx < bundle / 100, `index ${idx} bytes, bundle ${bundle} bytes`);
});

console.log(`${n} front page split tests passed`);
